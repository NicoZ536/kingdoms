//! Atlas metadata schema (RON).

use std::collections::BTreeMap;

use serde::{Deserialize, Serialize};

use crate::rendering::texture::Sampling;

/// `assets/atlases/index.ron`: the list of atlases to load.
#[derive(Clone, Debug, Default, Serialize, Deserialize)]
pub struct AtlasIndex {
    pub atlases: Vec<String>,
}

/// One atlas: an image plus named regions.
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct AtlasDef {
    /// Image file relative to the atlas metadata file.
    pub image: String,
    #[serde(default)]
    pub sampling: Sampling,
    #[serde(default = "default_true")]
    pub mipmaps: bool,
    /// Free-form provenance note (e.g. "placeholder generated by kingdoms_assetgen").
    #[serde(default)]
    pub source: String,
    pub sprites: BTreeMap<String, SpriteDef>,
    #[serde(default)]
    pub animations: BTreeMap<String, AnimationDef>,
}

fn default_true() -> bool {
    true
}

/// A sprite region inside an atlas.
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct SpriteDef {
    /// `(x, y, width, height)` in pixels.
    pub rect: (u32, u32, u32, u32),
    /// Normalised pivot, `(0.5, 1.0)` = bottom centre.
    #[serde(default = "default_anchor")]
    pub anchor: (f32, f32),
}

fn default_anchor() -> (f32, f32) {
    (0.5, 1.0)
}

/// A frame animation made of sprites of the same atlas.
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct AnimationDef {
    pub frames: Vec<String>,
    pub fps: f32,
    #[serde(default = "default_true")]
    pub looping: bool,
}

impl AtlasDef {
    /// Checks that every region lies inside the image and animations reference known sprites.
    pub fn validate(&self, name: &str, width: u32, height: u32) -> Result<(), String> {
        for (sprite, def) in &self.sprites {
            let (x, y, w, h) = def.rect;
            if w == 0 || h == 0 {
                return Err(format!("sprite '{sprite}' has zero size"));
            }
            if x + w > width || y + h > height {
                return Err(format!(
                    "sprite '{sprite}' rect {:?} exceeds image size {width}x{height}",
                    def.rect
                ));
            }
        }
        for (anim, def) in &self.animations {
            if def.frames.is_empty() {
                return Err(format!("animation '{anim}' has no frames"));
            }
            if let Some(missing) = def.frames.iter().find(|f| !self.sprites.contains_key(*f)) {
                return Err(format!("animation '{anim}' references unknown sprite '{missing}' in atlas '{name}'"));
            }
        }
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const SAMPLE: &str = r#"
        AtlasDef(
            image: "terrain.png",
            sprites: {
                "grass_0": (rect: (0, 0, 64, 48), anchor: (0.5, 0.3333)),
                "grass_1": (rect: (72, 0, 64, 48)),
            },
            animations: {
                "wave": (frames: ["grass_0", "grass_1"], fps: 4.0),
            },
        )
    "#;

    #[test]
    fn parses_and_validates() {
        let def: AtlasDef = ron::from_str(SAMPLE).unwrap();
        assert_eq!(def.sampling, Sampling::Pixel);
        assert!(def.mipmaps);
        assert_eq!(def.sprites["grass_1"].anchor, (0.5, 1.0));
        assert!(def.animations["wave"].looping);
        assert!(def.validate("terrain", 256, 64).is_ok());
        assert!(def.validate("terrain", 100, 64).is_err());
    }

    #[test]
    fn rejects_unknown_animation_frame() {
        let mut def: AtlasDef = ron::from_str(SAMPLE).unwrap();
        def.animations.get_mut("wave").unwrap().frames.push("nope".into());
        assert!(def.validate("terrain", 256, 64).is_err());
    }
}
