//! Shelf packer that writes a PNG atlas plus RON metadata in the engine's `AtlasDef` schema.

use std::collections::BTreeMap;
use std::path::Path;

use image::{Rgba, RgbaImage};
use kingdoms_engine::assets::{AnimationDef, AtlasDef, SpriteDef};
use kingdoms_engine::rendering::texture::{ATLAS_PADDING, Sampling};

use crate::draw::Canvas;

/// Largest atlas edge we generate (fits every GPU the game targets).
pub const MAX_ATLAS_SIZE: u32 = 4096;

/// Errors while building or writing an atlas.
#[derive(Debug, thiserror::Error)]
pub enum AtlasError {
    #[error("I/O error: {0}")]
    Io(#[from] std::io::Error),
    #[error("PNG encoding failed: {0}")]
    Image(#[from] image::ImageError),
    #[error("RON serialisation failed: {0}")]
    Ron(#[from] ron::Error),
    #[error("atlas '{atlas}' does not fit into {max}x{max} px")]
    TooLarge { atlas: String, max: u32 },
    #[error("atlas '{atlas}' contains sprite '{sprite}' twice")]
    DuplicateSprite { atlas: String, sprite: String },
    #[error("animation '{animation}' in atlas '{atlas}' references missing sprite '{frame}'")]
    MissingFrame { atlas: String, animation: String, frame: String },
}

/// Collects sprites and animations of one atlas.
pub struct AtlasBuilder {
    name: String,
    sprites: Vec<(String, Canvas, (f32, f32))>,
    animations: BTreeMap<String, AnimationDef>,
    sampling: Sampling,
    source: String,
}

/// Result of packing: atlas size and the top-left corner of every input rectangle.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Packing {
    pub width: u32,
    pub height: u32,
    pub positions: Vec<(u32, u32)>,
}

impl AtlasBuilder {
    /// New empty atlas named `name` (file names `<name>.png` / `<name>.ron`).
    pub fn new(name: &str, sampling: Sampling) -> Self {
        Self {
            name: name.to_owned(),
            sprites: Vec::new(),
            animations: BTreeMap::new(),
            sampling,
            source: "placeholder art generated by kingdoms_assetgen (replace with final art)".into(),
        }
    }

    /// Replaces the provenance note written to the RON `source` field.
    pub fn with_source(mut self, source: impl Into<String>) -> Self {
        self.source = source.into();
        self
    }

    /// Adds a sprite with a normalised anchor.
    pub fn add(&mut self, name: impl Into<String>, canvas: Canvas, anchor: (f32, f32)) {
        self.sprites.push((name.into(), canvas, anchor));
    }

    /// Atlas name (file stem and `<atlas>/` sprite prefix).
    pub fn name(&self) -> &str {
        &self.name
    }

    /// Sprite names added so far (in insertion order).
    #[cfg(test)]
    pub fn names(&self) -> Vec<&str> {
        self.sprites.iter().map(|(n, _, _)| n.as_str()).collect()
    }

    /// Animation names registered so far.
    #[cfg(test)]
    pub fn animation_names(&self) -> Vec<&str> {
        self.animations.keys().map(String::as_str).collect()
    }

    /// Registers a frame animation of sprites in this atlas.
    pub fn animation(&mut self, name: &str, frames: Vec<String>, fps: f32, looping: bool) {
        self.animations.insert(name.to_owned(), AnimationDef { frames, fps, looping });
    }

    /// Packs and renders the atlas image plus its metadata without touching the disk.
    pub fn build(&self) -> Result<(RgbaImage, AtlasDef), AtlasError> {
        let mut seen = std::collections::BTreeSet::new();
        for (n, _, _) in &self.sprites {
            if !seen.insert(n.as_str()) {
                return Err(AtlasError::DuplicateSprite { atlas: self.name.clone(), sprite: n.clone() });
            }
        }
        for (anim, def) in &self.animations {
            if let Some(f) = def.frames.iter().find(|f| !seen.contains(f.as_str())) {
                return Err(AtlasError::MissingFrame { atlas: self.name.clone(), animation: anim.clone(), frame: f.clone() });
            }
        }
        let sizes: Vec<(u32, u32)> = self.sprites.iter().map(|(_, c, _)| (c.img.width(), c.img.height())).collect();
        let names: Vec<&str> = self.sprites.iter().map(|(n, _, _)| n.as_str()).collect();
        let packing = pack(&sizes, &names, ATLAS_PADDING, MAX_ATLAS_SIZE)
            .ok_or_else(|| AtlasError::TooLarge { atlas: self.name.clone(), max: MAX_ATLAS_SIZE })?;
        let mut atlas = RgbaImage::from_pixel(packing.width, packing.height, Rgba([0, 0, 0, 0]));
        let mut sprites = BTreeMap::new();
        for (i, (name, canvas, anchor)) in self.sprites.iter().enumerate() {
            let (px, py) = packing.positions[i];
            blit_extruded(&mut atlas, &canvas.img, px, py, ATLAS_PADDING / 2);
            sprites.insert(name.clone(), SpriteDef { rect: (px, py, canvas.img.width(), canvas.img.height()), anchor: *anchor });
        }
        let def = AtlasDef {
            image: format!("{}.png", self.name),
            sampling: self.sampling,
            mipmaps: true,
            source: self.source.clone(),
            sprites,
            animations: self.animations.clone(),
        };
        Ok((atlas, def))
    }

    /// Packs all sprites and writes `<dir>/<name>.png` and `<dir>/<name>.ron`.
    /// Returns `(sprite count, width, height)`.
    pub fn write(self, dir: &Path) -> Result<(usize, u32, u32), AtlasError> {
        let (img, def) = self.build()?;
        std::fs::create_dir_all(dir)?;
        img.save(dir.join(format!("{}.png", self.name)))?;
        let text = ron::ser::to_string_pretty(&def, ron::ser::PrettyConfig::default().struct_names(true))?;
        std::fs::write(dir.join(format!("{}.ron", self.name)), text)?;
        println!("atlas '{}': {} sprites, {}x{}", self.name, self.sprites.len(), img.width(), img.height());
        Ok((self.sprites.len(), img.width(), img.height()))
    }
}

/// Packs rectangles with a skyline (bottom-left) packer, tallest first (ties by name), keeping
/// `pad` pixels around each one. Tries every power-of-two width up to `max` and keeps the
/// packing with the smallest power-of-two area (then the squarer one). Returns `None` if
/// nothing fits into `max × max`.
pub fn pack(sizes: &[(u32, u32)], names: &[&str], pad: u32, max: u32) -> Option<Packing> {
    let mut order: Vec<usize> = (0..sizes.len()).collect();
    order.sort_by(|&a, &b| sizes[b].1.cmp(&sizes[a].1).then(sizes[b].0.cmp(&sizes[a].0)).then(names[a].cmp(names[b])));
    let widest = sizes.iter().map(|s| s.0 + pad * 2).max().unwrap_or(0);
    let mut best: Option<Packing> = None;
    let mut width = 64u32;
    while width <= max {
        if width >= widest {
            if let Some(candidate) = skyline(sizes, &order, pad, width, max) {
                let area = |p: &Packing| u64::from(p.width) * u64::from(p.height);
                let better = match &best {
                    None => true,
                    Some(b) => {
                        area(&candidate) < area(b)
                            || (area(&candidate) == area(b) && candidate.width.abs_diff(candidate.height) < b.width.abs_diff(b.height))
                    }
                };
                if better {
                    best = Some(candidate);
                }
            }
        }
        width *= 2;
    }
    best
}

/// One skyline packing pass for a fixed atlas `width`.
fn skyline(sizes: &[(u32, u32)], order: &[usize], pad: u32, width: u32, max: u32) -> Option<Packing> {
    // Skyline segments (x, y, w) covering [pad, width) – the top edge of the occupied area.
    let mut sky: Vec<(u32, u32, u32)> = vec![(pad, pad, width - pad)];
    let mut positions = vec![(0u32, 0u32); sizes.len()];
    let mut bottom = pad;
    for &i in order {
        let (w, h) = (sizes[i].0 + pad, sizes[i].1 + pad);
        let mut choice: Option<(u32, u32, usize)> = None; // (y, x, segment index)
        for s in 0..sky.len() {
            let x = sky[s].0;
            if x + w > width {
                break;
            }
            // Highest skyline under [x, x + w).
            let mut y = 0;
            let mut covered = 0;
            for seg in &sky[s..] {
                if covered >= w {
                    break;
                }
                y = y.max(seg.1);
                covered = seg.0 + seg.2 - x;
            }
            if covered < w {
                continue;
            }
            if choice.is_none_or(|(cy, cx, _)| (y + h, x) < (cy + h, cx)) {
                choice = Some((y, x, s));
            }
        }
        let (y, x, _) = choice?;
        positions[i] = (x, y);
        bottom = bottom.max(y + h);
        // Replace the covered part of the skyline with the new top edge.
        let mut next: Vec<(u32, u32, u32)> = Vec::with_capacity(sky.len() + 2);
        for &(sx, sy, sw) in &sky {
            let (s0, s1) = (sx, sx + sw);
            if s1 <= x || s0 >= x + w {
                next.push((sx, sy, sw));
                continue;
            }
            if s0 < x {
                next.push((s0, sy, x - s0));
            }
            if s1 > x + w {
                next.push((x + w, sy, s1 - (x + w)));
            }
        }
        next.push((x, y + h, w));
        next.sort_by_key(|s| s.0);
        // Merge neighbours of equal height.
        let mut merged: Vec<(u32, u32, u32)> = Vec::with_capacity(next.len());
        for seg in next {
            match merged.last_mut() {
                Some(last) if last.1 == seg.1 && last.0 + last.2 == seg.0 => last.2 += seg.2,
                _ => merged.push(seg),
            }
        }
        sky = merged;
    }
    let height = bottom.next_power_of_two().max(64);
    (height <= max).then_some(Packing { width, height, positions })
}

/// Copies `img` and extrudes its border pixels by `extrude` pixels to avoid filtering seams.
fn blit_extruded(dst: &mut RgbaImage, img: &RgbaImage, px: u32, py: u32, extrude: u32) {
    let (w, h) = (i64::from(img.width()), i64::from(img.height()));
    let e = i64::from(extrude);
    for y in -e..h + e {
        for x in -e..w + e {
            let sx = x.clamp(0, w - 1) as u32;
            let sy = y.clamp(0, h - 1) as u32;
            let mut p = *img.get_pixel(sx, sy);
            if x < 0 || y < 0 || x >= w || y >= h {
                // Extruded pixels keep colour but only partial alpha so silhouettes stay crisp.
                p.0[3] /= 4;
            }
            let dx = i64::from(px) + x;
            let dy = i64::from(py) + y;
            if dx >= 0 && dy >= 0 && (dx as u32) < dst.width() && (dy as u32) < dst.height() {
                dst.put_pixel(dx as u32, dy as u32, p);
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::draw::rgb;

    fn overlaps(a: (u32, u32, u32, u32), b: (u32, u32, u32, u32), pad: u32) -> bool {
        a.0 < b.0 + b.2 + pad && b.0 < a.0 + a.2 + pad && a.1 < b.1 + b.3 + pad && b.1 < a.1 + a.3 + pad
    }

    #[test]
    fn packing_keeps_padding_and_bounds() {
        let sizes: Vec<(u32, u32)> = (0..60).map(|i| (16 + (i * 37) % 90, 12 + (i * 53) % 120)).collect();
        let names: Vec<String> = (0..60).map(|i| format!("s{i:02}")).collect();
        let refs: Vec<&str> = names.iter().map(String::as_str).collect();
        let p = pack(&sizes, &refs, 8, 4096).unwrap_or_else(|| panic!("must fit"));
        assert!(p.width.is_power_of_two() && p.height.is_power_of_two());
        let rects: Vec<(u32, u32, u32, u32)> = p.positions.iter().zip(&sizes).map(|(&(x, y), &(w, h))| (x, y, w, h)).collect();
        for (i, a) in rects.iter().enumerate() {
            assert!(a.0 >= 8 && a.1 >= 8 && a.0 + a.2 + 8 <= p.width && a.1 + a.3 + 8 <= p.height);
            for b in rects.iter().skip(i + 1) {
                assert!(!overlaps(*a, *b, 8), "{a:?} vs {b:?}");
            }
        }
    }

    #[test]
    fn packing_fails_when_too_large() {
        assert!(pack(&[(5000, 10)], &["huge"], 8, 4096).is_none());
        assert!(pack(&[(2000, 2000); 5], &["a", "b", "c", "d", "e"], 8, 4096).is_none());
    }

    #[test]
    fn build_rejects_duplicates_and_bad_animations() {
        let mut b = AtlasBuilder::new("t", Sampling::Pixel);
        b.add("x", Canvas::new(4, 4), (0.5, 0.5));
        b.add("x", Canvas::new(4, 4), (0.5, 0.5));
        assert!(matches!(b.build(), Err(AtlasError::DuplicateSprite { .. })));
        let mut b = AtlasBuilder::new("t", Sampling::Pixel);
        b.add("x", Canvas::new(4, 4), (0.5, 0.5));
        b.animation("walk", vec!["x".into(), "y".into()], 8.0, true);
        assert!(matches!(b.build(), Err(AtlasError::MissingFrame { .. })));
    }

    #[test]
    fn build_places_pixels_at_reported_rects() {
        let mut b = AtlasBuilder::new("t", Sampling::Smooth);
        let mut c = Canvas::new(3, 2);
        c.set(2, 1, rgb(0x00ff00));
        b.add("dot", c, (0.5, 1.0));
        let (img, def) = b.build().unwrap_or_else(|e| panic!("{e}"));
        let r = def.sprites.get("dot").map(|s| s.rect).unwrap_or_default();
        assert_eq!(img.get_pixel(r.0 + 2, r.1 + 1).0, [0, 255, 0, 255]);
        assert_eq!((r.2, r.3), (3, 2));
    }
}
