use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use atlas::{AtlasBuilder, AtlasError};
use serde::{Deserialize, Serialize};

/// File with the emitter points of the building sprites, next to the atlases.
const EMITTERS_FILE: &str = "emitters.ron";
/// The application icon in the assets folder (`tools/macos/make_app.sh` makes the `.icns`).
const APP_ICON_FILE: &str = "app_icon.png";

/// Emitter points of sprites (`assets/atlases/emitters.ron`, read by the game's particle
/// effects; schema in docs/assets.md): pixel offsets from the sprite's anchor, x to the right
/// and y downwards, of the unmirrored sprite.
#[derive(Debug, PartialEq, Serialize, Deserialize)]
struct EmitterPoints {
    /// Where smoke leaves a sprite (chimney tops, smoke holes, kiln vents), keyed `<atlas>/<sprite>`.
    smoke: BTreeMap<String, Vec<(f32, f32)>>,
}

impl EmitterPoints {
    fn generate() -> Self {
        Self { smoke: buildings::smoke_points() }
    }

    fn to_ron(&self) -> Result<String, ron::Error> {
        let body = ron::ser::to_string_pretty(self, ron::ser::PrettyConfig::default().struct_names(true))?;
        Ok(format!(
            "// Emitter points of sprites, generated by kingdoms_assetgen (docs/assets.md \"Emitter-Punkte\").\n\
             // Pixel offsets from the sprite anchor (x right, y down) of the unmirrored sprite.\n{body}\n"
        ))
    }
}

fn main() -> ExitCode {
    let assets = std::env::args().nth(1).map(PathBuf::from).unwrap_or_else(|| PathBuf::from("assets"));
    match run(&assets) {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("error: {e}");
            ExitCode::FAILURE
        }
    }
}

/// All atlases in load order (the order of `index.ron`).
fn atlases() -> Vec<AtlasBuilder> {
    vec![
        terrain::atlas(),
        terrain::overlay(),
        nature::atlas(),
        buildings::atlas(),
        roads::atlas(),
        fields::atlas(),
        characters::atlas(),
        effects::atlas(),
        icons::atlas(),
        ui::atlas(),
        buildings::lights_atlas(),
    ]
}

fn run(assets: &Path) -> Result<(), AtlasError> {
    let out = assets.join("atlases");
    std::fs::create_dir_all(&out)?;
    let mut names = Vec::new();
    let mut total = 0;
    for atlas in atlases() {
        names.push(atlas.name().to_owned());
        let (count, _, _) = atlas.write(&out)?;
        total += count;
    }
    let index = kingdoms_engine::assets::AtlasIndex { atlases: names };
    let text = ron::ser::to_string_pretty(&index, ron::ser::PrettyConfig::default().struct_names(true))?;
    std::fs::write(out.join("index.ron"), text)?;
    let emitters = EmitterPoints::generate();
    std::fs::write(out.join(EMITTERS_FILE), emitters.to_ron()?)?;
    println!("wrote {} ({} sprites with smoke points)", out.join(EMITTERS_FILE).display(), emitters.smoke.len());
    println!("wrote {} ({} atlases, {} sprites)", out.join("index.ron").display(), index.atlases.len(), total);
    let icon = assets.join(APP_ICON_FILE);
    app_icon::render().img.save(&icon)?;
    println!("wrote {} ({} × {} px)", icon.display(), app_icon::SIZE, app_icon::SIZE);
    Ok(())
}

#[cfg(test)]
mod tests {
    use std::collections::BTreeSet;

    use super::*;

    /// Sprite names required by docs/assets.md for each atlas.
    fn expected(atlas: &str) -> BTreeSet<String> {
        let mut s = BTreeSet::new();
        let seasons = ["spring", "summer", "autumn", "winter"];
        let dirs = ["ne", "se", "sw", "nw"];
        match atlas {
            "nature" => {
                for t in ["oak", "pine", "birch", "willow"] {
                    for season in seasons {
                        for stage in ["sapling", "young", "mature"] {
                            s.insert(format!("{t}_{season}_{stage}"));
                        }
                    }
                }
                s.insert("stump".into());
                for season in seasons {
                    s.insert(format!("bush_{season}"));
                }
                for i in 0..3 {
                    s.insert(format!("boulder_{i}"));
                }
                for d in ["stone", "iron", "coal", "clay", "sand", "gold", "fish"] {
                    s.insert(format!("deposit_{d}"));
                }
            }
            "buildings" => {
                for b in catalog::BUILDINGS {
                    s.insert(b.id.to_owned());
                }
                for (b, t) in catalog::footprints() {
                    for stage in 0..3 {
                        s.insert(format!("construction_{b}x{t}_{stage}"));
                    }
                    s.insert(format!("rubble_{b}x{t}"));
                }
                for id in buildings::WORK_LOOPS {
                    for f in 0..buildings::WORK_FRAMES {
                        s.insert(format!("{id}_work_{f}"));
                    }
                }
                for id in buildings::WINTER_VARIANTS {
                    s.insert(format!("{id}_winter"));
                }
            }
            "roads" => {
                for k in ["path", "gravel", "road", "paved", "trade_road"] {
                    for m in 0..16 {
                        s.insert(format!("{k}_{m}"));
                    }
                }
                for m in 0..16 {
                    s.insert(format!("wall_{m}"));
                }
                for x in ["bridge_x", "bridge_y", "gate_x", "gate_y"] {
                    s.insert(x.into());
                }
            }
            "fields" => {
                s.insert("soil".into());
                s.insert("pasture".into());
                for c in ["wheat", "barley", "vegetables", "orchard"] {
                    for i in 0..5 {
                        s.insert(format!("{c}_{i}"));
                    }
                }
                s.insert("orchard_bare".into());
            }
            "characters" => {
                for r in characters::ROLES {
                    for d in dirs {
                        for f in 0..4 {
                            s.insert(format!("{r}_{d}_{f}"));
                        }
                    }
                }
                let loops = characters::WORK_ROLES.iter().map(|r| (r, "work")).chain(characters::ATTACK_ROLES.iter().map(|r| (r, "attack")));
                for (r, kind) in loops {
                    for d in dirs {
                        for f in 0..characters::ACT_FRAMES {
                            s.insert(format!("{r}_{d}_{kind}_{f}"));
                        }
                    }
                }
                for r in characters::GATHER_ROLES {
                    for g in characters::Gather::ALL {
                        for d in dirs {
                            for f in 0..characters::ACT_FRAMES {
                                s.insert(format!("{r}_{d}_{}_{f}", g.name()));
                            }
                        }
                    }
                }
                s.insert("banner".into());
            }
            "effects" => {
                for i in 0..6 {
                    s.insert(format!("smoke_{i}"));
                }
                for i in 0..4 {
                    s.insert(format!("fire_{i}"));
                }
                for i in 0..3 {
                    s.insert(format!("dust_{i}"));
                }
                for x in ["rain", "snowflake", "sparkle"] {
                    s.insert(x.into());
                }
                for i in 0..4 {
                    s.insert(format!("leaf_{i}"));
                }
                for k in 0..effects::ARROW_DIRS {
                    s.insert(format!("arrow_{k}"));
                }
                s.insert("stone".into());
            }
            "icons" => {
                for r in catalog::RESOURCES {
                    s.insert(format!("res_{r}"));
                }
                for b in catalog::BUILDINGS {
                    s.insert(format!("bld_{}", b.id));
                }
                for u in icons::UI_ICONS {
                    s.insert(format!("ui_{u}"));
                }
                for i in 0..crate::palette::KINGDOM_COLORS.len() {
                    s.insert(format!("crest_{i}"));
                }
            }
            "ui" => {
                for x in ["parchment", "wood", "gold_frame", "button_normal", "button_hover", "button_pressed", "button_disabled"] {
                    s.insert(x.into());
                }
            }
            "lights" => {
                for id in buildings::lit_buildings() {
                    s.insert(id.into());
                }
            }
            _ => {}
        }
        s
    }

    #[test]
    fn atlases_contain_exactly_the_documented_sprites() {
        for atlas in atlases() {
            let want = expected(atlas.name());
            if want.is_empty() {
                continue; // terrain / overlay are covered by the terrain module.
            }
            let have: BTreeSet<String> = atlas.names().into_iter().map(str::to_owned).collect();
            let missing: Vec<_> = want.difference(&have).collect();
            let extra: Vec<_> = have.difference(&want).collect();
            assert!(missing.is_empty(), "{}: missing {missing:?}", atlas.name());
            assert!(extra.is_empty(), "{}: undocumented {extra:?}", atlas.name());
        }
    }

    #[test]
    fn animations_are_registered() {
        let all = atlases();
        let find = |n: &str| all.iter().find(|a| a.name() == n).map(|a| a.animation_names().into_iter().map(str::to_owned).collect::<Vec<_>>()).unwrap_or_default();
        let chars = find("characters");
        let loops = characters::WORK_ROLES.len() + characters::ATTACK_ROLES.len() + characters::GATHER_ROLES.len() * characters::Gather::ALL.len();
        assert_eq!(chars.len(), (characters::ROLES.len() + loops) * 4);
        assert!(chars.contains(&"man_se_pickaxe".to_owned()) && chars.contains(&"woman_nw_rod".to_owned()));
        assert!(chars.contains(&"cart_nw_walk".to_owned()));
        assert!(chars.contains(&"builder_se_work".to_owned()) && chars.contains(&"archer_nw_attack".to_owned()));
        let buildings = find("buildings");
        assert!(buildings.contains(&"mill_work".to_owned()) && buildings.contains(&"smelter_work".to_owned()));
        let fx = find("effects");
        assert!(fx.contains(&"smoke".to_owned()) && fx.contains(&"fire".to_owned()));
    }

    #[test]
    fn emitter_points_round_trip_and_name_building_sprites() {
        let points = EmitterPoints::generate();
        let text = match points.to_ron() {
            Ok(t) => t,
            Err(e) => panic!("emitter points do not serialise: {e}"),
        };
        match ron::from_str::<EmitterPoints>(&text) {
            Ok(back) => assert_eq!(back, points),
            Err(e) => panic!("emitters.ron does not parse: {e}"),
        }
        let buildings = expected("buildings");
        for name in points.smoke.keys() {
            let sprite = name.strip_prefix("buildings/").unwrap_or(name);
            assert!(buildings.contains(sprite), "{name} is not a building sprite");
        }
    }

    #[test]
    fn every_atlas_packs_within_limits_and_is_deterministic() {
        let first: Vec<_> = atlases().iter().map(|a| a.build().map(|(img, _)| img)).collect();
        let second: Vec<_> = atlases().iter().map(|a| a.build().map(|(img, _)| img)).collect();
        for (a, b) in first.iter().zip(&second) {
            match (a, b) {
                (Ok(a), Ok(b)) => {
                    assert!(a.width() <= atlas::MAX_ATLAS_SIZE && a.height() <= atlas::MAX_ATLAS_SIZE);
                    assert_eq!(a.as_raw(), b.as_raw(), "non-deterministic output");
                }
                (Err(e), _) | (_, Err(e)) => panic!("atlas failed to build: {e}"),
            }
        }
    }
}
