//! `kingdoms_assetgen` — generates the placeholder sprite atlases used until final art exists.
//!
//! Usage: `cargo run -p kingdoms_assetgen --release -- [assets_dir]` (default: `assets`).
//! Output is deterministic: running it twice produces identical files. The sprite names follow
//! `docs/assets.md` ("Namenskonventionen"); final art can replace the PNGs as long as names and
//! anchors are kept.

