#!/usr/bin/env bash
# Builds the macOS app bundle Kingdoms.app from this repository.
#
#   tools/macos/make_app.sh [--target <triple>] [--universal] [--out <dir>] [--no-build]
#
# Steps: `cargo build --release` (optionally for one target or for Apple Silicon and Intel at
# once), then Kingdoms.app with the binary in Contents/MacOS, `assets/` and `data/` in
# Contents/Resources (the game looks there first when it runs from a bundle), an Info.plist
# (bundle id, version from Cargo.toml, Retina support, minimum macOS version, category games)
# and Kingdoms.icns made from assets/app_icon.png with sips and iconutil. Finally the bundle
# gets an ad-hoc signature (codesign), which Apple Silicon requires for every executable.
#
# Needs macOS with the Xcode command line tools (sips, iconutil, codesign, lipo, plutil) and
# Rust (rustup). On other systems the bundle is assembled without icon and signature (for
# checking the layout only).
set -euo pipefail

APP_NAME="Kingdoms"
EXE="kingdoms"
BUNDLE_ID="${KINGDOMS_BUNDLE_ID:-org.kingdoms.game}"
MIN_MACOS="11.0"

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
OUT="$ROOT/target/macos"
TARGET=""
UNIVERSAL=0
BUILD=1

usage() {
    cat <<'EOF'
Usage: tools/macos/make_app.sh [options]

  --target <triple>  build for this target, e.g. aarch64-apple-darwin (Apple Silicon) or
                     x86_64-apple-darwin (Intel); default: the machine's own
  --universal        build for both and join them with lipo (both targets must be installed:
                     rustup target add aarch64-apple-darwin x86_64-apple-darwin)
  --out <dir>        where Kingdoms.app is written (default: target/macos)
  --no-build         use the release binary that is already built
  -h, --help         this text

Environment: KINGDOMS_BUNDLE_ID overrides the bundle identifier (default org.kingdoms.game).
EOF
}

fail() {
    echo "make_app.sh: $*" >&2
    exit 1
}

have() {
    command -v "$1" >/dev/null 2>&1
}

while [ $# -gt 0 ]; do
    case "$1" in
        --target)
            [ $# -ge 2 ] || fail "--target needs a target triple"
            TARGET="$2"
            shift 2
            ;;
        --universal)
            UNIVERSAL=1
            shift
            ;;
        --out)
            [ $# -ge 2 ] || fail "--out needs a directory"
            OUT="$2"
            shift 2
            ;;
        --no-build)
            BUILD=0
            shift
            ;;
        -h | --help)
            usage
            exit 0
            ;;
        *)
            usage >&2
            fail "unknown option: $1"
            ;;
    esac
done
if [ "$UNIVERSAL" = 1 ] && [ -n "$TARGET" ]; then
    fail "--universal and --target exclude each other"
fi

# The version of the workspace (Cargo.toml, [workspace.package]).
VERSION="$(awk '/^\[workspace\.package\]/ { section = 1; next } /^\[/ { section = 0 } section && $1 == "version" { gsub(/"/, "", $3); print $3; exit }' "$ROOT/Cargo.toml")"
[ -n "$VERSION" ] || fail "cannot read the version from $ROOT/Cargo.toml"

# Path of the release binary for target $1 (empty: the machine's own).
binary_for() {
    if [ -n "$1" ]; then
        printf '%s\n' "$ROOT/target/$1/release/$EXE"
    else
        printf '%s\n' "$ROOT/target/release/$EXE"
    fi
}

build_for() {
    if [ -n "$1" ]; then
        (cd "$ROOT" && cargo build --release --bin "$EXE" --target "$1")
    else
        (cd "$ROOT" && cargo build --release --bin "$EXE")
    fi
}

if [ "$UNIVERSAL" = 1 ]; then
    TARGETS=(aarch64-apple-darwin x86_64-apple-darwin)
else
    TARGETS=("$TARGET")
fi
if [ "$BUILD" = 1 ]; then
    have cargo || fail "cargo not found – install Rust with rustup (https://rustup.rs)"
    for t in "${TARGETS[@]}"; do
        build_for "$t"
    done
fi

APP="$OUT/$APP_NAME.app"
CONTENTS="$APP/Contents"
echo "Kingdoms $VERSION -> $APP"
rm -rf "$APP"
mkdir -p "$CONTENTS/MacOS" "$CONTENTS/Resources"

# The executable (one architecture, or both joined).
if [ "$UNIVERSAL" = 1 ]; then
    have lipo || fail "lipo not found (Xcode command line tools: xcode-select --install)"
    BIN_ARM="$(binary_for "${TARGETS[0]}")"
    BIN_X86="$(binary_for "${TARGETS[1]}")"
    [ -f "$BIN_ARM" ] && [ -f "$BIN_X86" ] || fail "release binaries missing ($BIN_ARM, $BIN_X86)"
    lipo -create -output "$CONTENTS/MacOS/$EXE" "$BIN_ARM" "$BIN_X86"
else
    BIN="$(binary_for "$TARGET")"
    [ -f "$BIN" ] || fail "release binary missing: $BIN (run without --no-build)"
    cp "$BIN" "$CONTENTS/MacOS/$EXE"
fi
chmod 755 "$CONTENTS/MacOS/$EXE"

# Game content: the game finds Contents/Resources/{assets,data} next to Contents/MacOS.
for dir in assets data; do
    [ -d "$ROOT/$dir" ] || fail "$ROOT/$dir is missing"
    cp -R "$ROOT/$dir" "$CONTENTS/Resources/"
done

# Icon: Kingdoms.icns from the 1024 px PNG (generated by tools/assetgen).
ICON_PNG="$ROOT/assets/app_icon.png"
ICON_KEY=""
if [ ! -f "$ICON_PNG" ]; then
    echo "warning: $ICON_PNG missing (cargo run -p kingdoms_assetgen --release -- assets); no icon" >&2
elif have sips && have iconutil; then
    WORK="$(mktemp -d)"
    trap 'rm -rf "$WORK"' EXIT
    ICONSET="$WORK/$APP_NAME.iconset"
    mkdir -p "$ICONSET"
    for size in 16 32 128 256 512; do
        sips -z "$size" "$size" "$ICON_PNG" --out "$ICONSET/icon_${size}x${size}.png" >/dev/null
        double=$((size * 2))
        sips -z "$double" "$double" "$ICON_PNG" --out "$ICONSET/icon_${size}x${size}@2x.png" >/dev/null
    done
    iconutil -c icns "$ICONSET" -o "$CONTENTS/Resources/$APP_NAME.icns"
    ICON_KEY="    <key>CFBundleIconFile</key>
    <string>$APP_NAME</string>"
else
    echo "warning: sips/iconutil not found (not macOS?); bundle without icon" >&2
fi

cat >"$CONTENTS/Info.plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleName</key>
    <string>$APP_NAME</string>
    <key>CFBundleDisplayName</key>
    <string>KINGDOMS – Rise of an Empire</string>
    <key>CFBundleIdentifier</key>
    <string>$BUNDLE_ID</string>
    <key>CFBundleExecutable</key>
    <string>$EXE</string>
    <key>CFBundlePackageType</key>
    <string>APPL</string>
    <key>CFBundleShortVersionString</key>
    <string>$VERSION</string>
    <key>CFBundleVersion</key>
    <string>$VERSION</string>
    <key>CFBundleInfoDictionaryVersion</key>
    <string>6.0</string>
    <key>CFBundleDevelopmentRegion</key>
    <string>de</string>
$ICON_KEY
    <key>LSMinimumSystemVersion</key>
    <string>$MIN_MACOS</string>
    <key>LSApplicationCategoryType</key>
    <string>public.app-category.strategy-games</string>
    <key>NSHighResolutionCapable</key>
    <true/>
    <key>NSSupportsAutomaticGraphicsSwitching</key>
    <true/>
    <key>NSHumanReadableCopyright</key>
    <string>KINGDOMS – Rise of an Empire</string>
</dict>
</plist>
EOF
if have plutil; then
    plutil -lint "$CONTENTS/Info.plist" >/dev/null || fail "Info.plist is invalid"
fi

# Apple Silicon runs only signed code; an ad-hoc signature is enough on this Mac.
if have codesign; then
    codesign --force --sign - "$APP"
    codesign --verify "$APP" || fail "the signature of $APP does not verify"
else
    echo "warning: codesign not found (not macOS?); bundle not signed" >&2
fi

echo "done: $APP"
echo "start with: open \"$APP\" (saves and settings: ~/Library/Application Support/$APP_NAME)"
